def _is_documentation_or_meta_file(file_path: str) -> bool:
    """Return True when the changed file is docs/config/meta rather than source code."""
    if not file_path:
        return True

    normalized = file_path.replace("\\", "/").lower().strip()
    if normalized.startswith("docs/") or "/docs/" in normalized:
        return True

    file_name = normalized.split("/")[-1]
    if file_name in {"readme", "readme.md", "license", "license.md", "changelog.md"}:
        return True

    for ext in DOC_META_EXTENSIONS:
        if normalized.endswith(ext):
            return True

    return False


def _normalize_path(path: str) -> str:
    return (path or "").replace("\\", "/").strip().lower()


def _is_github_workflow_file(file_path: str) -> bool:
    """Return True if the path points to a GitHub Actions workflow file."""
    normalized = _normalize_path(file_path)
    return normalized.startswith(".github/workflows/") and (
        normalized.endswith(".yml") or normalized.endswith(".yaml")
    )


def _is_suspicious_automation_workflow_file(file_path: str) -> bool:
    """
    Detect workflow files likely intended for automated committing/pushing.
    Example: .github/workflows/auto commit.yml
    """
    if not _is_github_workflow_file(file_path):
        return False

    workflow_name = _normalize_path(file_path).split("/")[-1]
    return any(pattern in workflow_name for pattern in SUSPICIOUS_AUTOMATION_WORKFLOW_PATTERNS)


def _normalize_identity(value: str) -> str:
    """Normalize author/email strings for reliable bot marker matching."""
    if not value:
        return ""
    return re.sub(r"\s+", "", value.strip().lower())


def _detect_automated_author(author: str, email: str = "") -> Optional[str]:
    """
    Detect known automated commit authors (GitHub Actions, bot users, etc.).
    Returns the matched marker when automation is detected.
    """
    author_norm = _normalize_identity(author)
    email_norm = _normalize_identity(email)

    for marker in AUTOMATED_AUTHOR_MARKERS:
        if marker in author_norm or marker in email_norm:
            return marker

    return None


def _detect_ai_bots_in_contributors(author_stats: dict, total_commits: int) -> dict:
    """
    Detect AI tools, bots, or automated systems in contributor list.
    This catches students using Lovable, Bolt, Cursor, etc. for commits.
    
    Returns:
        {
            'has_ai_bots': bool,
            'ai_bot_contributors': [
                {'name': str, 'commits': int, 'share': float, 'tool': str}
            ]
        }
    """
    ai_bot_contributors = []
    
    for author, stats in author_stats.items():
        name_lower = author.strip().lower()
        commits = stats.get("commits", 0) if isinstance(stats, dict) else 0
        share = round((commits / max(1, total_commits)) * 100, 1)

        # Explicit automation identities (e.g., github-actions, actions[bot])
        automated_marker = _detect_automated_author(author)
        if automated_marker:
            ai_bot_contributors.append({
                'name': author,
                'commits': commits,
                'share': share,
                'tool': automated_marker.upper()
            })
            continue
        
        # Check if author name matches AI bot names
        for bot_name in AI_BOT_NAMES:
            if bot_name in name_lower:
                ai_bot_contributors.append({
                    'name': author,
                    'commits': commits,
                    'share': share,
                    'tool': bot_name.upper()
                })
                break
    
    return {
        'has_ai_bots': len(ai_bot_contributors) > 0,
        'ai_bot_contributors': ai_bot_contributors
    }


def _detect_suspicious_authors(author_stats: dict, total_commits: int) -> dict:
    """
    Detect authors with suspicious/generic names that don't identify a real person.
    
    Returns:
        {
            'has_suspicious': bool,
            'suspicious_authors': [
                {'name': str, 'commits': int, 'share': float, 'reason': str}
            ]
        }
    """
    suspicious_authors = []
    
    for author, stats in author_stats.items():
        name_lower = author.strip().lower()
        commits = stats.get("commits", 0) if isinstance(stats, dict) else 0
        share = round((commits / max(1, total_commits)) * 100, 1)
        reason = None
        
        # Check against known suspicious names
        if name_lower in SUSPICIOUS_AUTHOR_NAMES:
            reason = f"Generic default name '{author}'"
        
        # Check against machine-name patterns
        if not reason:
            for pattern in SUSPICIOUS_NAME_PATTERNS:
                if re.match(pattern, author, re.IGNORECASE):
                    reason = f"Machine-generated name '{author}'"
                    break
        
        # Check for single character names
        if not reason and len(author.strip()) <= 1:
            reason = f"Single character name '{author}'"
        
        if reason:
            suspicious_authors.append({
                'name': author,
                'commits': commits,
                'share': share,
                'reason': reason
            })
    
    return {
        'has_suspicious': len(suspicious_authors) > 0,
        'suspicious_authors': suspicious_authors
    }


def _detect_contribution_imbalance(author_stats: dict, total_commits: int) -> dict:
    """
    Detect when one author dominates commit distribution.
    
    Thresholds:
        - 3+ members: >70% from one author = imbalance
        - 2 members: >80% from one author = imbalance
        - 1 member: skip (solo projects)
    
    Severity:
        - mild: >60% (3+ members) or >75% (2 members)
        - moderate: >70% (3+ members) or >80% (2 members)
        - severe: >85% regardless of team size
    
    Returns:
        {
            'has_imbalance': bool,
            'severity': str,  # 'mild', 'moderate', 'severe'
            'dominant_author': str,
            'dominant_share': float,
            'details': [{'author': str, 'commits': int, 'share': float}]
        }
    """
    num_members = len(author_stats)
    
    # Skip for solo projects
    if num_members <= 1:
        return {
            'has_imbalance': False,
            'severity': 'none',
            'dominant_author': '',
            'dominant_share': 0,
            'details': []
        }
    
    # Build details list
    details = []
    for author, stats in author_stats.items():
        commits = stats.get("commits", 0) if isinstance(stats, dict) else 0
        share = round((commits / max(1, total_commits)) * 100, 1)
        details.append({'author': author, 'commits': commits, 'share': share})
    
    details.sort(key=lambda x: x['share'], reverse=True)
    
    dominant = details[0]
    dominant_share = dominant['share']
    
    # Determine severity based on team size
    severity = 'none'
    has_imbalance = False
    
    if dominant_share >= 85:
        severity = 'severe'
        has_imbalance = True
    elif num_members >= 3:
        if dominant_share >= 70:
            severity = 'moderate'
            has_imbalance = True
        elif dominant_share >= 60:
            severity = 'mild'
            has_imbalance = True
    elif num_members == 2:
        if dominant_share >= 80:
            severity = 'moderate'
            has_imbalance = True
        elif dominant_share >= 75:
            severity = 'mild'
            has_imbalance = True
    
    return {
        'has_imbalance': has_imbalance,
        'severity': severity,
        'dominant_author': dominant['author'],
        'dominant_share': dominant_share,
        'details': details
    }


def _calculate_entropy(text: str) -> float:
    if not text: return 0.0
    prob = [float(text.count(c)) / len(text) for c in dict.fromkeys(list(text))]
    return -sum([p * math.log(p) / math.log(2.0) for p in prob])

def _is_dependency_folder(file_path: str) -> bool:
    """Check if file is in a dependency/build folder"""
    excluded_folders = [
        'node_modules/', 'vendor/', 'packages/', '.next/',
        'dist/', 'build/', 'target/', '__pycache__/', '.venv/',
        'venv/', 'env/', 'coverage/', '.pytest_cache/', 'bower_components/',
        '.gradle/', 'out/', 'bin/', 'obj/', 'Debug/', 'Release/'
    ]
    return any(folder in file_path for folder in excluded_folders)

def _is_generated_file(file_path: str) -> bool:
    """Check if file is generated/compiled"""
    generated_extensions = [
        '.min.js', '.min.css', '.bundle.js', '.map',
        '.pyc', '.class', '.o', '.so', '.dll', '.exe',
        '.jar', '.war', '.ear', '.wasm'
    ]
    return any(file_path.endswith(ext) for ext in generated_extensions)


def _is_generic_commit_message(msg: str) -> bool:
    """Check if commit message is generic/lazy"""
    msg_clean = msg.strip().lower()
    
    # Check exact matches
    if msg_clean in GENERIC_COMMIT_MESSAGES:
        return True
    
    # Check if message is too short (< 3 chars)
    if len(msg_clean) < 3:
        return True
    
    # Check if message is only repeated characters (e.g., "aaaaaa", "......")
    if len(set(msg_clean)) == 1:
        return True
    
    # Check if message is only numbers
    if msg_clean.isdigit():
        return True
    
    return False


def _detect_ai_tool_in_message(msg: str) -> str:
    """Check if commit message mentions AI tools"""
    msg_lower = msg.lower()
    for keyword in AI_TOOL_KEYWORDS:
        if keyword in msg_lower:
            return keyword
    return None


def _is_whitespace_only_change(files_changed: list) -> bool:
    """Detect if commit only changes whitespace (can't fully detect without diff, heuristic)"""
    # Heuristic: If many files changed but very few lines, likely whitespace/formatting
    if len(files_changed) > 5:
        total_changes = sum(f.get('additions', 0) + f.get('deletions', 0) for f in files_changed)
        avg_changes_per_file = total_changes / len(files_changed)
        
        # If average is < 2 lines per file, likely just whitespace/formatting
        if avg_changes_per_file < 2:
            return True
    
    return False


def _detect_timestamp_manipulation(commit_date: datetime, current_time: datetime) -> tuple:
    """Detect suspicious timestamp patterns"""
    issues = []
    
    # Check if commit is in the future
    if commit_date > current_time:
        days_future = (commit_date - current_time).days
        issues.append(f"Future-dated ({days_future} days ahead)")
    
    # Check if commit is suspiciously old (backdated beyond reasonable project age)
    days_ago = (current_time - commit_date).days
    if days_ago > 730:  # More than 2 years old
        issues.append(f"Suspiciously old ({days_ago} days ago)")
    
    return tuple(issues)

def _calculate_commit_quality(commit_data: dict) -> dict:
    """
    Calculate quality metrics for a commit.
    Separates truly fake/suspicious commits from quality issues.
    
    Returns: {
        'is_fake': bool,  # True for empty/repeated/suspicious commits
        'has_quality_issues': bool,  # True for dependency dumps, generated files
        'fake_reasons': list,  # Serious issues (empty, repeated)
        'quality_issues': list,  # Tolerable issues (deps, generated files)
        'quality_score': float (0-1),
        'real_additions': int,
        'fake_additions': int
    }
    """
    additions = commit_data['additions']
    deletions = commit_data['deletions']
    files_changed = commit_data['files_changed']
    stats_reliable = commit_data.get('stats_reliable', True)
    
    fake_reasons = []  # Serious issues - not tolerable
    quality_issues = []  # Tolerable but need improvement
    real_additions = 0
    fake_additions = 0
    
    # Check 1: Empty commit (TRULY FAKE - not tolerable)
    if stats_reliable and additions == 0 and deletions == 0:
        fake_reasons.append("Empty Commit (No Changes)")
        return {
            'is_fake': True,
            'has_quality_issues': False,
            'fake_reasons': fake_reasons,
            'quality_issues': [],
            'quality_score': 0.0,
            'real_additions': 0,
            'fake_additions': 0
        }
    
    # Check 2: Massive addition (QUALITY ISSUE - poor practice but tolerable)
    if additions > 50_000:
        quality_issues.append(f"Large Dependency Dump ({additions:,} lines)")
    elif additions > 10_000:
        quality_issues.append(f"Large Addition ({additions:,} lines - likely dependencies)")
    
    # Check 3: Too many files (QUALITY ISSUE)
    if len(files_changed) > 100:
        quality_issues.append(f"Too Many Files ({len(files_changed)} files - likely dependencies)")
    
    # Check 4: Analyze file types (QUALITY ISSUES)
    for file_info in files_changed:
        file_path = file_info['path']
        file_additions = file_info['additions']
        
        if _is_dependency_folder(file_path):
            fake_additions += file_additions
            if 'Dependencies Committed' not in quality_issues:
                quality_issues.append("Dependencies Committed (node_modules/vendor should be in .gitignore)")
        elif _is_generated_file(file_path):
            fake_additions += file_additions
            if 'Generated Files Committed' not in quality_issues:
                quality_issues.append("Generated Files Committed (.min.js/.pyc should be in .gitignore)")
        else:
            real_additions += file_additions
    
    # Calculate quality score
    total_additions = additions
    if total_additions > 0:
        quality_score = real_additions / total_additions
    else:
        quality_score = 1.0
    
    # Determine flags
    has_quality_issues = len(quality_issues) > 0
    is_fake = False  # We've moved empty checks above; this is now reserved for forensics
    
    return {
        'is_fake': is_fake,
        'has_quality_issues': has_quality_issues,
        'fake_reasons': fake_reasons,
        'quality_issues': quality_issues,
        'quality_score': quality_score,
        'real_additions': real_additions,
        'fake_additions': fake_additions
    }

def analyze_commits(repo_path: str) -> Dict[str, Any]:
    try:
        repo = Repo(repo_path)
    except Exception as e:
        return {"error": str(e), "total_commits": 0}

    # --- 1. ENHANCED BRANCH ANALYSIS ---
    all_branches = []
    try:
        local_branches = [h.name for h in repo.heads]
        remote_branches = [r.name for r in repo.remotes.origin.refs] if repo.remotes else []
        all_branches = list(set(local_branches + remote_branches))
        print(f"      [LOCAL] Local branches found: {local_branches}")
        print(f"      [REMOTE] Remote branches found: {remote_branches}")
    except Exception as e:
        print(f"      [ERROR] Error fetching branches: {e}")
        all_branches = ["master"]

    # Branch-wise Author Breakdown & Detailed Branch Info
    # Structure: {'main': {'Alice': 10, 'Bob': 2}, 'dev': {'Alice': 5}}
    branch_stats = defaultdict(Counter)
    branch_details = {}  # Detailed info per branch
    
    # Identify main branch
    main_branch_names = ['main', 'master', 'trunk', 'develop']
    main_branch = None
    for branch_name in main_branch_names:
        if branch_name in [b.name for b in repo.heads]:
            main_branch = branch_name
            break
    
    if not main_branch and repo.heads:
        main_branch = repo.heads[0].name  # Fallback to first branch
    
    print(f"      [MAIN] Identified main branch: {main_branch}")
    print(f"      [COUNT] Total branches to analyze: {len(repo.heads)}")
    
    # Analyze each branch in detail
    for b in repo.heads:
        branch_name = b.name
        print(f"      [ANALYZE] Analyzing branch: {branch_name}")
        try:
            branch_commits = list(repo.iter_commits(branch_name, max_count=200))
            
            # Author stats for this branch
            branch_authors = Counter()
            last_commit_date = None
            first_commit_date = None
            total_commits_in_branch = len(branch_commits)
            
            for c in branch_commits:
                branch_stats[branch_name][c.author.name] += 1
                branch_authors[c.author.name] += 1
                
                # Track dates
                commit_date = c.committed_datetime
                if last_commit_date is None or commit_date > last_commit_date:
                    last_commit_date = commit_date
                if first_commit_date is None or commit_date < first_commit_date:
                    first_commit_date = commit_date
            
            # Check if branch is merged into main
            is_merged = False
            merge_status = "Not Merged"
            days_since_last_commit = None
            
            if main_branch and branch_name != main_branch:
                try:
                    # Check if branch commits are in main branch history
                    main_commits = set(c.hexsha for c in repo.iter_commits(main_branch, max_count=500))
                    branch_commit_shas = set(c.hexsha for c in branch_commits[:50])  # Check recent commits
                    
                    # If most branch commits are in main, it's merged
                    if branch_commit_shas and len(branch_commit_shas & main_commits) / len(branch_commit_shas) > 0.7:
                        is_merged = True
                        merge_status = "Merged"
                    else:
                        merge_status = "Unmerged"
                except Exception as merge_err:
                    print(f"      [WARN] Error checking merge status for {branch_name}: {merge_err}")
                    merge_status = "Unknown"
            elif branch_name == main_branch:
                merge_status = "Main Branch"
            
            # Determine if branch is active (commits in last 14 days)
            is_active = False
            if last_commit_date:
                days_since_last_commit = (datetime.now(last_commit_date.tzinfo) - last_commit_date).days
                is_active = days_since_last_commit <= 14
            
            # Store detailed branch info
            branch_details[branch_name] = {
                "name": branch_name,
                "totalCommits": total_commits_in_branch,
                "authors": dict(branch_authors.most_common()),
                "primaryAuthor": branch_authors.most_common(1)[0][0] if branch_authors else "Unknown",
                "lastCommitDate": last_commit_date.isoformat() if last_commit_date else None,
                "firstCommitDate": first_commit_date.isoformat() if first_commit_date else None,
                "isActive": is_active,
                "daysSinceLastCommit": days_since_last_commit,
                "mergeStatus": merge_status,
                "isMerged": is_merged,
                "isMainBranch": branch_name == main_branch
            }
            print(f"      [OK] Branch '{branch_name}' analyzed: {total_commits_in_branch} commits, status: {merge_status}")
        except Exception as e:
            print(f"      [ERROR] Error analyzing branch {branch_name}: {e}")
            import traceback
            traceback.print_exc()
    
    print(f"      [COMPLETE] Branch analysis complete: {len(branch_details)} branches with details")

    # --- 2. DEEP FORENSICS SETUP ---
    try:
        # Get full history from all references
        raw_commits = list(repo.iter_commits('--all', max_count=5000))
    except:
        raw_commits = []
    
    # Calculate total commits early (needed by AI bot detection at line 781)
    total_commits = len(raw_commits)

    # Storage for analysis
    author_stats = defaultdict(lambda: {
        "commits": 0, "lines_added": 0, "lines_deleted": 0, 
        "active_days": set(), "file_types": Counter()
    })
    
    # Store individual commits with details
    all_commits = []
    
    # Period Trackers: { '2023-10-01': {'Alice': 5, 'Bob': 1} }
    daily_activity = defaultdict(Counter)
    weekly_activity = defaultdict(Counter)
    monthly_activity = defaultdict(Counter)
    
    suspicious_commits = []
    dummy_commit_count = 0
    fake_commits = []  # Truly fake: empty, repeated, suspicious
    quality_issue_commits = []  # Tolerable: dependencies, generated files
    real_commits = []
    total_real_additions = 0
    total_fake_additions = 0
    prev_commit = None
    
    # NEW: Track commit flooding (too many commits in short time)
    commit_timestamps = []  # Store (datetime, author) for flooding detection
    ai_tool_mentions = []  # Track commits mentioning AI tools
    generic_message_count = 0
    timestamp_issues_count = 0
    whitespace_only_count = 0
    docs_only_commit_count = 0
    code_commit_count = 0
    
    # Sort Oldest -> Newest for proper timeline analysis
    raw_commits.sort(key=lambda x: x.committed_datetime)
    
    # Get current time for timestamp validation
    current_time = datetime.now(raw_commits[0].committed_datetime.tzinfo if raw_commits else None)

    for c in raw_commits:
        author = c.author.name
        date = c.committed_datetime
        msg = c.message.strip()
        
        # Track commit timestamps for flooding detection
        commit_timestamps.append((date, author))
        
        # Keys for aggregation
        day_key = date.strftime('%Y-%m-%d')
        week_key = date.strftime('%Y-W%U')
        month_key = date.strftime('%Y-%m')
        
        # A. PERIOD AGGREGATION
        daily_activity[day_key][author] += 1
        weekly_activity[week_key][author] += 1
        monthly_activity[month_key][author] += 1
        
        # B. AUTHOR TOTALS
        author_stats[author]["commits"] += 1
        author_stats[author]["active_days"].add(day_key)
        
        # C. FILE & STATS ANALYSIS
        added, deleted = 0, 0
        files_changed = []
        stats_reliable = False
        try:
            # Check what files changed
            for file_path, stats in c.stats.files.items():
                ext = file_path.split('.')[-1] if '.' in file_path else 'no_ext'
                author_stats[author]["file_types"][ext] += 1
                added += stats.get('insertions', 0)
                deleted += stats.get('deletions', 0)
                files_changed.append({
                    "path": file_path,
                    "additions": stats.get('insertions', 0),
                    "deletions": stats.get('deletions', 0)
                })
            stats_reliable = True
        except:
            # Fallback to aggregate totals when per-file details are unavailable.
            # This avoids false "empty commit" flags from missing Git stats.
            try:
                total_stats = c.stats.total or {}
                added = total_stats.get('insertions', 0) or 0
                deleted = total_stats.get('deletions', 0) or 0
                stats_reliable = True
            except:
                stats_reliable = False

        author_stats[author]["lines_added"] += added
        author_stats[author]["lines_deleted"] += deleted
        
        # Store individual commit details
        all_commits.append({
            "hash": c.hexsha,
            "short_hash": c.hexsha[:7],
            "author": author,
            "email": c.author.email,
            "message": msg,
            "date": date.isoformat(),
            "additions": added,
            "deletions": deleted,
            "files_changed": files_changed
        })

        # D. FORENSIC CHECKS
        is_suspicious = False
        reasons = []

        # NEW: Calculate commit quality
        commit_quality = _calculate_commit_quality({
            'additions': added,
            'deletions': deleted,
            'files_changed': files_changed,
            'stats_reliable': stats_reliable
        })

        if files_changed:
            has_code_files = any(not _is_documentation_or_meta_file(f.get("path", "")) for f in files_changed)
            if has_code_files:
                code_commit_count += 1
            else:
                docs_only_commit_count += 1
        
        # 1. Dummy Commit (0 files changed) - TRULY FAKE
        if stats_reliable and added == 0 and deleted == 0:
            is_suspicious = True
            reasons.append("Empty Commit (No Changes)")
            dummy_commit_count += 1
        
        # 2. Generic/Lazy Commit Message - tracked for health scoring but NOT treated as fake
        if _is_generic_commit_message(msg):
            reasons.append(f"Generic Message: '{msg[:30]}'")
            generic_message_count += 1
        
        # 3. AI Tool Mentioned in Message - REMOVED (False Positive)
        # NOTE: Mentioning AI tools in commit messages is LEGITIMATE when working with AI APIs.
        # For example: "Fix: Use GEMINI_API_KEY instead of OPENAI_API_KEY" is a valid commit.
        # AI tools should ONLY be detected in CONTRIBUTOR NAMES (checked separately at line 787).
        # Tracking for informational purposes only (not marking as suspicious):
        ai_tool = _detect_ai_tool_in_message(msg)
        if ai_tool:
            ai_tool_mentions.append({
                'hash': c.hexsha[:7],
                'author': author,
                'tool': ai_tool,
                'message': msg[:50]
            })

        # 3.5 Automated author identities (github-actions/dependabot/etc.) - TRULY FAKE
        automated_marker = _detect_automated_author(author, c.author.email)
        if automated_marker:
            is_suspicious = True
            reasons.append(f"Automated Bot Commit ({automated_marker})")

        # 4. Timestamp Manipulation - TRULY FAKE
        timestamp_issues = _detect_timestamp_manipulation(date, current_time)
        if timestamp_issues:
            is_suspicious = True
            for issue in timestamp_issues:
                reasons.append(f"Timestamp Issue: {issue}")
            timestamp_issues_count += 1
        
        # 5. Whitespace-Only Changes - TRULY FAKE
        if _is_whitespace_only_change(files_changed):
            is_suspicious = True
            reasons.append("Whitespace-Only Changes")
            whitespace_only_count += 1

        # 5.5 Suspicious workflow automation file (e.g., auto commit.yml) - TRULY FAKE
        suspicious_workflows = [
            f.get("path", "") for f in files_changed
            if _is_suspicious_automation_workflow_file(f.get("path", ""))
        ]
        if suspicious_workflows:
            is_suspicious = True
            for workflow_file in suspicious_workflows[:2]:
                reasons.append(f"Automated Commit Workflow ({workflow_file})")
             
        # 6. Repeated Commit (Same msg + Same content change + Close time) - TRULY FAKE
        if prev_commit:
            time_diff = (date - prev_commit.committed_datetime).total_seconds()
            same_msg = msg == prev_commit.message.strip()
            same_author = author == prev_commit.author.name
            
            # Enhanced: Check if same message AND same author AND close time
            if same_msg and same_author and time_diff < 300:
                is_suspicious = True
                reasons.append(f"Repeated Commit ({int(time_diff)}s apart)")
            
            # If superhuman speed (< 10s) between ANY two commits
            # EXCLUDE automatic merge commits (they're instant and normal)
            is_merge_commit = len(c.parents) > 1
            if time_diff < 10 and same_author and not is_merge_commit:
                is_suspicious = True
                reasons.append("Superhuman Speed (<10s)")
        
        # 7. Code Dump Detection - DISABLED
        # Note: Large initial commits are NORMAL and expected behavior.
        # Quality issues (dependencies, generated files) are tracked separately as "quality_issue_commits"
        # and do NOT make a commit "fake". Only truly suspicious behavior (empty commits, repeated commits,
        # AI tools, generic messages, etc.) should flag commits as fake.
        # Large file additions are handled by the quality assessment system, not forensics.
        
        # Track truly fake commits (empty, repeated, suspicious)
        if is_suspicious or commit_quality['is_fake']:
            fake_commits.append({
                "hash": c.hexsha[:7],
                "author": author,
                "msg": msg[:50],
                "date": date.isoformat(),
                "reasons": reasons + commit_quality['fake_reasons'],
                "additions": added
            })
            suspicious_commits.append({
                "hash": c.hexsha[:7],
                "author": author,
                "msg": msg[:30],
                "reasons": reasons
            })
        
        # Track quality issues separately (dependencies, generated files)
        if commit_quality['has_quality_issues']:
            quality_issue_commits.append({
                "hash": c.hexsha[:7],
                "author": author,
                "msg": msg[:50],
                "date": date.isoformat(),
                "issues": commit_quality['quality_issues'],
                "additions": added,
                "fake_additions": commit_quality['fake_additions']
            })
            total_fake_additions += commit_quality['fake_additions']
        
        # Track generic message commits as quality issues (lazy but not malicious)
        elif _is_generic_commit_message(msg) and not is_suspicious and not commit_quality['is_fake']:
            quality_issue_commits.append({
                "hash": c.hexsha[:7],
                "author": author,
                "msg": msg[:50],
                "date": date.isoformat(),
                "issues": [f"Generic Commit Message: '{msg[:40]}'"],
                "additions": added,
                "fake_additions": 0
            })
        
        # Track real commits
        if not is_suspicious and not commit_quality['is_fake'] and not commit_quality['has_quality_issues']:
            real_commits.append(c.hexsha[:7])
        
        # Always track real additions
        total_real_additions += commit_quality['real_additions']

        prev_commit = c
    
    # --- 2.3 COMMIT FLOODING DETECTION ---
    # Detect if any author committed too many times in a short period
    # Normal development: 10-20 commits/hour is fine (fixing bugs, iterating features)
    # Flooding: 30+ commits/hour indicates automated scripts or spam
    flooding_issues = []
    author_hourly_commits = defaultdict(lambda: defaultdict(int))
    
    for commit_date, commit_author in commit_timestamps:
        hour_key = commit_date.strftime('%Y-%m-%d %H:00')
        author_hourly_commits[commit_author][hour_key] += 1
    
    for author, hourly_counts in author_hourly_commits.items():
        for hour, count in hourly_counts.items():
            if count > 30:  # More than 30 commits in one hour (increased from 10)
                flooding_issues.append({
                    'author': author,
                    'hour': hour,
                    'commit_count': count,
                    'reason': f'{count} commits in 1 hour (automated/scripted)'
                })
    
    # --- 2.4 AI BOT DETECTION IN CONTRIBUTORS ---
    ai_bot_result = _detect_ai_bots_in_contributors(author_stats, total_commits)

    # --- 2.5 QUALITY ISSUE FORGIVENESS ---
    # Post-process quality_issue_commits to see if the user quickly rectified a mistake
    # (e.g. accidentally mass-committing node_modules, then deleting them).
    # NOTE: We only forgive quality issues, NOT truly fake commits (empty, repeated, etc.)
    final_quality_issues = []
    for qc in quality_issue_commits:
        is_forgiven = False
        # Only forgive quality issues, not truly fake commits
        if any("Dependencies Committed" in iss or "Generated Files" in iss or "Large" in iss for iss in qc["issues"]):
            # Find the index of this commit in all_commits
            qc_idx = next((i for i, c in enumerate(all_commits) if c["short_hash"] == qc["hash"]), -1)
            
            if qc_idx != -1:
                # Look ahead up to 3 commits by the same author
                lookahead_window = all_commits[qc_idx + 1 : qc_idx + 6]  # check next 5 commits total
                author_subsequent = [c for c in lookahead_window if c["author"] == qc["author"]][:3]
                
                for sc in author_subsequent:
                    # If the subsequent commit deletes at least 80% as many lines as the quality issue commit added
                    # AND it is primarily a deletion commit (additions < 20% of deletions)
                    if sc["deletions"] >= qc["additions"] * 0.8 and sc["additions"] < sc["deletions"] * 0.2:
                        is_forgiven = True
                        break
        
        if is_forgiven:
            # Revert the penalties associated with this commit
            total_fake_additions -= qc["fake_additions"]
            # We don't add real_additions back because the code was deleted anyway
        else:
            final_quality_issues.append(qc)
            
    # Update quality issue statistics after forgiveness
    quality_issue_commits = final_quality_issues
    
    # --- 3. CALCULATE "WINNERS" FOR PERIODS ---
    def get_period_winners(activity_dict):
        """Returns who won the most periods (e.g., who was top contributor for the most days)"""
        winners = Counter()
        for period, counts in activity_dict.items():
            if counts:
                top_auth = counts.most_common(1)[0][0] # Get author with max commits that period
                winners[top_auth] += 1
        return winners.most_common(1)[0] if winners else ("None", 0)

    top_daily_winner, daily_wins = get_period_winners(daily_activity)
    top_weekly_winner, weekly_wins = get_period_winners(weekly_activity)
    top_monthly_winner, monthly_wins = get_period_winners(monthly_activity)

    # --- 4. FORMAT FINAL STATS ---
    final_author_stats = {}
    total_relevance = 0.0
    
    for auth, data in author_stats.items():
        # Get top 3 file types modified by this author
        top_files = [f"{ext} ({cnt})" for ext, cnt in data["file_types"].most_common(3)]
        
        # Calculate author relevance score
        # Base: 1 point per commit. 
        # Bonus: 0.01 point per line changed (cap at 5 points per commit avg) to reward effort
        # This is a heuristic proxy for "relevance" if we don't store per-commit scores in loop
        # BETTER: Use accumulated relevance from loop if we added it.
        
        # Retroactively applying relevance logic since we didn't track it in the first loop pass in this edit
        # To do this properly, I should have modified the loop. 
        # But for minimal diff, let's estimate relevance here or fix the loop in a separate Edit.
        # WAIT, I can simply calculate a derived score here.
        
        commits_count = data["commits"]
        lines = data["lines_added"] + data["lines_deleted"]
        active_days = len(data["active_days"])
        
        # Relevance: Commits + (Lines / 100) + (Active Days * 2)
        # Capped to avoid skewing by massive auto-generated files
        relevance = (commits_count * 1.0) + (min(lines, 10000) / 100.0) + (active_days * 2.0)
        total_relevance += relevance

        final_author_stats[auth] = {
            "commits": commits_count,
            "lines_changed": lines,
            "active_days_count": active_days,
            "top_file_types": ", ".join(top_files),
            "relevance_score": round(relevance, 1)
        }

    # Calculate fake commit ratios (total_commits already defined at line 558)
    fake_commit_count = len(fake_commits)
    fake_commit_ratio = (fake_commit_count / max(1, total_commits)) * 100

    # Guardrail: docs-only or no-code repos should not be penalized as fake commits.
    # These may be early-stage repos with README/config history but no executable code yet.
    docs_only_repo = total_commits > 0 and code_commit_count == 0
    low_activity_inactive_repo = total_commits <= 1 and code_commit_count == 0
    if total_commits == 0 or docs_only_repo or low_activity_inactive_repo:
        fake_commits = []
        fake_commit_count = 0
        fake_commit_ratio = 0.0
        dummy_commit_count = 0
    
    # Calculate quality issue ratio (separately)
    quality_issue_count = len(quality_issue_commits)
    quality_issue_ratio = (quality_issue_count / max(1, total_commits)) * 100
    
    # Calculate inflation ratio
    expected_lines = total_commits * 150  # 150 lines per commit average
    actual_lines = total_real_additions + total_fake_additions
    inflation_ratio = actual_lines / max(1, expected_lines)
    
    # --- NEW: Detect suspicious author names ---
    suspicious_author_result = _detect_suspicious_authors(final_author_stats, total_commits)
    
    # --- NEW: Detect contribution imbalance ---
    imbalance_result = _detect_contribution_imbalance(final_author_stats, total_commits)
    
    # Determine health status (separated: fake commits are critical, quality issues are warnings)
    if low_activity_inactive_repo:
        # User rule: one-commit/no-content repos are inactive, not fake.
        commit_health = "Inactive"
    elif (fake_commit_ratio > 50 or 
          ai_bot_result['has_ai_bots'] or  # AI bots are CRITICAL
          (imbalance_result['severity'] == 'severe' and suspicious_author_result['has_suspicious'])):
        commit_health = "Critical"
    elif (fake_commit_ratio > 30 or 
          quality_issue_ratio > 60 or  # High quality issues are a concern
          len(flooding_issues) > 0 or  # Commit flooding detected
          generic_message_count > total_commits * 0.3 or  # >30% generic messages
          imbalance_result['has_imbalance'] or 
          suspicious_author_result['has_suspicious']):
        commit_health = "At Risk"
    elif (quality_issue_ratio > 30 or 
          generic_message_count > total_commits * 0.15):  # >15% generic messages
        commit_health = "Needs Improvement"
    else:
        commit_health = "Healthy"
        
    # Get last commit date for inactivity penalty
    last_commit_date = None
    if raw_commits:
        last_commit_date = raw_commits[-1].committed_datetime.isoformat()

    return {
        "total_commits": len(raw_commits),
        "branch_count": len(all_branches),
        "branches": all_branches,
        "branch_activity": {k: dict(v) for k, v in branch_stats.items()}, # Branch-wise breakdown
        "branch_details": branch_details,  # NEW: Detailed branch information
        "main_branch": main_branch,  # NEW: Identified main branch
        "author_stats": final_author_stats,
        "all_commits": all_commits,  # Individual commit details
        "dummy_commits": dummy_commit_count,
        "suspicious_list": suspicious_commits,
        "total_relevance": round(total_relevance, 1),
        
        # Fake commit detection (truly fake: empty, repeated, suspicious)
        "fake_commits": fake_commits,
        "fake_commit_count": fake_commit_count,
        "fake_commit_ratio": round(fake_commit_ratio, 1),
        
        # Quality issues (tolerable: dependencies, generated files)
        "quality_issue_commits": quality_issue_commits,
        "quality_issue_count": quality_issue_count,
        "quality_issue_ratio": round(quality_issue_ratio, 1),
        
        # Overall commit quality
        "real_commit_count": len(real_commits),
        "total_real_additions": total_real_additions,
        "total_fake_additions": total_fake_additions,
        "inflation_ratio": round(inflation_ratio, 2),
        "commit_health": commit_health,
        "last_commit_date": last_commit_date,
        
        # Suspicious author detection
        "suspicious_authors": suspicious_author_result,
        
        # AI bot detection in contributors
        "ai_bot_detection": ai_bot_result,
        
        # AI tool mentions in commit messages
        "ai_tool_mentions": ai_tool_mentions,
        "ai_tool_mention_count": len(ai_tool_mentions),
        
        # Contribution imbalance detection
        "contribution_imbalance": imbalance_result,
        
        # Additional fake commit metrics
        "generic_message_count": generic_message_count,
        "generic_message_ratio": round((generic_message_count / max(1, total_commits)) * 100, 1),
        "timestamp_issues_count": timestamp_issues_count,
        "whitespace_only_count": whitespace_only_count,
        "docs_only_commit_count": docs_only_commit_count,
        "code_commit_count": code_commit_count,
        "docs_only_repo": docs_only_repo,
        "low_activity_inactive_repo": low_activity_inactive_repo,
        "commit_flooding": flooding_issues,
        "has_commit_flooding": len(flooding_issues) > 0,
        
        # Period Winners
        "consistency_stats": {
            "top_daily": f"{top_daily_winner} (Led {daily_wins} days)",
            "top_weekly": f"{top_weekly_winner} (Led {weekly_wins} weeks)",
            "top_monthly": f"{top_monthly_winner} (Led {monthly_wins} months)"
        }
    }
