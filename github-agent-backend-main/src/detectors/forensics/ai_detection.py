"""
AI detection utilities for commit forensics.
Detects AI tools, bots, and automated systems in commits.
"""

from typing import Dict, List


# AI tools and bots that students might use for automated commits
AI_BOT_NAMES = {
    "lovable", "bolt", "v0", "cursor", "github-copilot", "copilot",
    "replit", "stackblitz", "codesandbox", "glitch", "vercel",
    "netlify", "railway", "render", "fly", "heroku",
    "dependabot", "renovate", "greenkeeper", "snyk",
    "coderabbit", "deepsource", "codecov", "sonarcloud",
    "gitpod", "codespaces", "goland", "pycharm", "webstorm",
    "ai-assistant", "auto-commit", "auto-push", "bot-commit"
}


# AI tool keywords in commit messages
AI_TOOL_KEYWORDS = [
    "lovable", "bolt.new", "bolt.diy", "v0.dev", "cursor.ai",
    "github copilot", "copilot generated", "ai generated", "ai-generated",
    "generated by ai", "auto-generated", "autogenerated",
    "replit agent", "stackblitz ai", "ai assistant",
    "chatgpt", "claude", "gemini", "gpt-4", "gpt-3",
    "code assistant", "ai coding", "ai helper"
]


def detect_ai_bots_in_contributors(author_stats: dict, total_commits: int) -> dict:
    """
    Detect AI tools, bots, or automated systems in contributor list.
    
    Args:
        author_stats: Dictionary mapping author names to their commit stats
        total_commits: Total number of commits in repository
        
    Returns:
        {
            'has_ai_bots': bool,
            'ai_bot_contributors': List of detected AI bot contributors
        }
    """
    ai_bot_contributors = []
    
    for author, stats in author_stats.items():
        name_lower = author.strip().lower()
        commits = stats.get("commits", 0) if isinstance(stats, dict) else 0
        share = round((commits / max(1, total_commits)) * 100, 1)
        
        # Check if author name matches AI bot names
        for bot_name in AI_BOT_NAMES:
            if bot_name in name_lower:
                ai_bot_contributors.append({
                    'name': author,
                    'commits': commits,
                    'share': share,
                    'tool': bot_name.upper()
                })
                break
    
    return {
        'has_ai_bots': len(ai_bot_contributors) > 0,
        'ai_bot_contributors': ai_bot_contributors
    }


def detect_ai_tool_mentions(commits: List[dict]) -> List[dict]:
    """
    Detect mentions of AI tools in commit messages.
    
    Args:
        commits: List of commit dictionaries with 'message', 'hash', 'author'
        
    Returns:
        List of commits mentioning AI tools
    """
    ai_mentions = []
    
    for commit in commits:
        msg = commit.get("message", "").lower()
        
        for keyword in AI_TOOL_KEYWORDS:
            if keyword in msg:
                ai_mentions.append({
                    'hash': commit.get("hash", "")[:7],
                    'tool': keyword,
                    'author': commit.get("author", "Unknown"),
                    'message': commit.get("message", "")[:50]
                })
                break  # Only count once per commit
    
    return ai_mentions
