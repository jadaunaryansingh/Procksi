-- Run ONLY if you previously applied an older 001 that had teams.project_title.
-- Moves titles into public.projects and drops the legacy column.

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  team_id bigint not null unique references public.teams (id) on delete cascade,
  title varchar(512) not null,
  description text
);

do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'teams' and column_name = 'project_title'
  ) then
    insert into public.projects (team_id, title)
    select id, coalesce(nullif(trim(project_title), ''), name || ' Project')
    from public.teams
    on conflict (team_id) do update set title = excluded.title;
    alter table public.teams drop column project_title;
  end if;
end $$;
