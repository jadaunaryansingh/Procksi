-- Panel + Mentor dashboard — MENTOR & PANEL DASHBOARD.pdf
-- Tables: users, teams, projects, evaluations, slots, github_data, alerts
-- Plus: evaluation_parameters, evaluation_drafts

create table if not exists public.teams (
  id bigint generated by default as identity primary key,
  name varchar(255) not null
);

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  team_id bigint not null unique references public.teams (id) on delete cascade,
  title varchar(512) not null,
  description text
);

create table if not exists public.github_data (
  id bigint generated by default as identity primary key,
  team_id bigint not null unique references public.teams (id) on delete cascade,
  repository_url varchar(1024),
  default_branch varchar(128),
  open_pull_requests integer,
  commit_count_30d integer,
  last_commit_at timestamptz,
  raw_json text
);

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  email varchar(255) not null unique,
  hashed_password varchar(255) not null,
  role varchar(32) not null default 'panel',
  panel_id varchar(64)
);

create index if not exists ix_users_panel_id on public.users (panel_id);

create table if not exists public.alerts (
  id bigint generated by default as identity primary key,
  panel_id varchar(64),
  user_id bigint references public.users (id) on delete set null,
  team_id bigint references public.teams (id) on delete set null,
  alert_type varchar(64) not null,
  title varchar(255) not null,
  body text,
  created_at timestamptz not null default now(),
  acknowledged_at timestamptz
);

create index if not exists ix_alerts_panel_id on public.alerts (panel_id);

create table if not exists public.slots (
  id bigint generated by default as identity primary key,
  panel_id varchar(64) not null,
  team_id bigint not null references public.teams (id) on delete cascade,
  venue varchar(255),
  slot_label varchar(64) not null,
  window_start timestamptz not null,
  window_end timestamptz not null,
  status varchar(32) not null default 'Upcoming'
);

create index if not exists ix_slots_panel_id on public.slots (panel_id);

create table if not exists public.evaluations (
  id bigint generated by default as identity primary key,
  panel_id varchar(64) not null,
  team_id bigint not null references public.teams (id) on delete cascade,
  scores_json text not null,
  remarks text not null,
  submitted_at timestamptz not null,
  receipt_id varchar(64) not null unique,
  locked boolean not null default true,
  constraint uq_eval_panel_team unique (panel_id, team_id)
);

create index if not exists ix_evaluations_panel_id on public.evaluations (panel_id);

create table if not exists public.evaluation_drafts (
  id bigint generated by default as identity primary key,
  panel_id varchar(64) not null,
  team_id bigint not null references public.teams (id) on delete cascade,
  scores_json text not null default '{}',
  remarks text not null default '',
  updated_at timestamptz not null,
  constraint uq_draft_panel_team unique (panel_id, team_id)
);

create index if not exists ix_evaluation_drafts_panel_id on public.evaluation_drafts (panel_id);

create table if not exists public.evaluation_parameters (
  id bigint generated by default as identity primary key,
  category varchar(512) not null,
  criterion_name varchar(512) not null,
  max_marks integer not null
);

alter table public.teams enable row level security;
alter table public.projects enable row level security;
alter table public.github_data enable row level security;
alter table public.users enable row level security;
alter table public.alerts enable row level security;
alter table public.slots enable row level security;
alter table public.evaluations enable row level security;
alter table public.evaluation_drafts enable row level security;
alter table public.evaluation_parameters enable row level security;
